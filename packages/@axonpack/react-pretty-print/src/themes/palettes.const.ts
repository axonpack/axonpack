import type { PrettyPrintTheme } from './theme.const';

/*
 * The palette set. Ordinary source — edit a colour if you want to, the tests below keep it honest.
 *
 * These were not taken from anywhere. Each one is constructed from three choices, and the rules are
 * written down here rather than in a script so that a hand-written addition matches the rest:
 *
 * `DARK_THEME` and `LIGHT_THEME` sit outside that scheme and come first. They are the only
 * achromatic pair — every constructed palette is tinted toward its base hue, so neither a plain
 * grey nor a plain white is reachable through the recipe — and they are what the renderers default
 * to, which reads better in a signature than any `<hue>_<mode>_<character>` name would.
 *
 * NAME      <hue>_<mode>_<character>_THEME
 *
 * HUE       crimson 355  amber 30  gold 50  citron 75  lime 95  emerald 140  jade 160  teal 180
 *           cyan 190  azure 205  cobalt 225  sapphire 245  indigo 260  violet 275  magenta 300
 *           rose 330
 *
 * MODE      dark  — background near the bottom of the lightness range, text near the top
 *           light — the reverse
 *
 * CHARACTER muted — low token saturation
 *           vivid — high token saturation
 *           soft  — background pulled toward the middle, so the whole palette is lower contrast
 *           crisp — background pushed to the extreme, tokens held to a 7:1 ratio
 *
 * Within a palette, each role sits at a fixed offset from the base hue, spaced at least 40 degrees
 * apart so no two roles read as the same colour: key +0, accent +40, string +85, number +140,
 * comment +180 (desaturated — it carries the least information on the row), keyword +225, tag +290.
 * `boolean` shares `number`'s colour deliberately: both are literals, and painting `2` and `true`
 * differently is noise rather than information.
 *
 * `fontFamily` is `monospace` in every palette here, which is correct on the web and on Android and
 * **wrong on iOS**: `monospace` is an Android family name, iOS finds no font by it, and it falls back
 * to the proportional system font without a word. Nothing in this package can call `Platform.select`
 * — importing a platform is the one thing the design rules out — so a React Native caller has to
 * override the token:
 *
 *     const MONO = Platform.select({ ios: 'Menlo', default: 'monospace' });
 *     const theme = { ...DARK_THEME, fontFamily: MONO };
 *
 * `example-native/App.tsx` does exactly that. A caller on the DOM needs nothing.
 *
 * `matchHighlight` is the palette's own `accent` with an alpha, so a highlighted run belongs to the
 * palette and can never collide with a token colour. Translucent on purpose: the text sits on top of
 * it and has to stay readable. The alpha is the lowest at which the band is actually visible against
 * that palette's background — 25% for all but one of these.
 *
 * `punctuation`, `toggle` and `null` share one muted tone — the palette's own text pulled toward its
 * own background — so a collapsed preview stays recessive instead of competing with real content.
 *
 * Every colour clears a WCAG contrast ratio against its own background: 4.5:1 for body text, 7:1 on
 * `crisp`, and never below 3:1 for any token. That is not a convention, it is asserted for all 130
 * palettes in `themes.test.ts`, along with keys never matching strings and a hue-named palette
 * actually being that hue. Tune whatever you like; those tests will tell you if it stops holding.
 */

